// queryDefaults は TanStack Query の既定。本番とテストで同じものを使う。
//
// テストだけ違う設定にすると、キャッシュに起因する不具合がテストに映らない。
// 実際「検索した履歴が遷移しても反映されない」不具合を、テスト側の
// staleTime が 0（＝毎回取り直す）だったために取り逃した。
export const queryDefaults = {
  // 献立マスタも履歴も秒単位で変わるものではない。
  // 画面を切り替えるたびに取り直さないよう少し寝かせる。
  // そのぶん、サーバの状態を変える操作は明示的に無効化すること。
  staleTime: 30_000,
  // 401 は再試行しても通らないため、既定の3回リトライは無駄。
  retry: 1,
  refetchOnWindowFocus: false,
} as const
